/**
 * Time-triggered actions, used by Skynet bot to perform operations without human interaction (Using Cronjobs)
 *
 * @author Wavetrex Infinity <wavetrex@gmail.com>
 * @package CargoConnect
 * @subpackage DataModels
 * @version 2020.09.29
 */
class App_Model_Actions extends MVC_Model
{
	/**
	 * Now many actions are allowed to be returned by a scan in one cycle.
	 * - This is necessary to prevent overloading the executors with too many operations
	 * - (but the queue must be monitored to see if the limit is too small). Let's start with 10
	 */
	const	SCAN_LIMIT = 10;

	// Failures or Self-Check codes
	const	RESULT_PLUGIN_INSTANCE_FAIL =		-1, 
			RESULT_PLUGIN_OPERATION_NOTFOUND =	-2,
			RESULT_PLUGIN_OPERATION_FAIL =		-3, // When the plugin operation threw an exception (wasn't able to execute for unknown reason)
			RESULT_PLUGIN_INVALID_RETURN =		-4, // When the plugin returns something else than an array containing the result
			//- If the plugin has an internal log it should be checked

			// NEAR codes (Non-Error Archival Reason)
			NEAR_DATE_IN_THE_PAST =				-1,
			NEAR_END_BEFORE_TRIGGER =			-2	// Task action stage is set to "end" before the action was triggered (for example, because task is Completed)
			;

	private static $valid_executors = array(
		'task'	// Task related actions - warning, deadline, overdue, closure
	);

	/**
	 * Instances of Executor plugin objects (not sure if needed)
	 * @var array
	 */
	protected static $plugin_instances = array();

	/**
	 * Create a new future action.
	 * - Actions are triggered when found in the ACT table and their trigger_dt is lower than current datetime
	 *
	 * @param DateTime $trigger_dt When to trigger execution
	 * @param string $executor Plugin that is being used to perform the action when trigerred
	 * @param string $operation Name of the operation (depends on plugin)
	 * @param int $creator_id (Optional) ID of the entity that called for this action (depends on plugin)
	 * @param array $action_data (Optional) Will be encoded as JSON and stored. Used by the plugin, and can have arbitrary format (but must match what the plugin understands)
	 * -- Operation, Creator ID, Actions are optional because some executor plugins might have one unique action without any information (General maintenance actions)
	 * @param int $org_id (Optional) For which organization is this action stored (in most cases it will match the creator entity), or null for system actions
	 * @param string $comment_append (Optional) Text based comment (appended to the part auto-generated by the plugin)
	 */
	public function create(DateTime $trigger_dt, $executor, $operation = null, $creator_id = null, $action_data = null, $org_id = null, $comment_append = null)
	{
		if(empty($executor) || !in_array($executor, self::$valid_executors))
			return MVC_Core::$debug-> dump(sprintf("Invalid Action execution plugin: %s", $executor), __METHOD__, 'error');

		// Instance the plugin to verify if the passed data is correct
		$plugin = MVC_Core::factory_Plugin("action", $executor);
		if(!$plugin instanceof App_Plugin_Action)
			return MVC_Core::$debug-> dump(sprintf("Failed to instance Action execution plugin: %s", $executor), __METHOD__, 'error');

		$check = $plugin-> verify_Action($operation, $action_data, (string)$comment_append);
		if(!$check)
			return MVC_Core::$debug-> dump(sprintf("Invalid action data for operation: %s in execution plugin: %s", $operation, $executor), __METHOD__, 'error');

		// Special check, the new Action trigger should not be in the past (returns the special value -1, which is not necesarely an error, but the Action is not recorded
		// If an action is needed "as soon as possible", it should be recorded with at least 1 second after "now", so at the next scan cycle it will be found as triggered.
		$now = new DateTime();
		if($trigger_dt < $now) {
			MVC_Core::$debug-> dump(sprintf("Specified Trigger DateTime %s is already in the past", $trigger_dt-> format("Y-m-d H:i:s")), __METHOD__, 'warning');
			return -1;
		}

		// Everything ready, create the record
		$data = array(
			'org_id'=> $org_id,
			'create_dt'=> $now-> format("Y-m-d H:i:s"),
			'trigger_dt'=> $trigger_dt-> format("Y-m-d H:i:s"),
			'executor'=> $executor,
			'operation'=> $check['operation'],
			'creator_id'=> $creator_id,
			'data_json'=> is_null($check['data'])? null: json_encode($check['data']),
			'comment'=> $check['comment']
		);
		$q=QueryFactory::insert()
		-> table(MVC_Core::$db-> tab['act'])
		-> values($data);

		$r = MVC_Core::$db-> query($q);
		if(!$r)
			return MVC_Core::$debug-> dump("Error creating the action record", __METHOD__, 'error');

		return MVC_Core::$db-> insert_id;
	}

	/**
	 * Reads an action by it's ID (raw data, no processing)
	 *
	 * @param int $act_id
	 * @return array
	 */
	public function read($act_id)
	{
		$q=QueryFactory::select()
		-> table(MVC_Core::$db-> tab['act']) // Complete readout
		-> where("`id` = ?", $act_id)
		-> limit(1);

		$r = MVC_Core::$db-> query($q);
		if(!$r || count($r)==0)
			return false; // Action not found or database error

		return $r-> current();
	}

	/**
	 * Updates an existing action.
	 * - May change trigger_dt, operation, the actions data and the comment
	 * - Not possible to change create_dt or the executor plugin. If these need to be changed, the action must be deleted and recreated
	 *
	 * @param int $act_id
	 * @param DateTime $trigger_dt Must be DateTime for comparing with "Now"
	 * @param string $operation
	 * @param mixed $action_data Update to the Action record's "data_json" field
	 * @param string $comment
	 * @param bool $read_check
	 * @return boolean
	 */
	public function update($act_id, DateTime $trigger_dt = null, $operation = null, $action_data = null, $comment = null, $read_check = true)
	{
		if($read_check) {
			// Attempt to read the existing Action (will be used for checking, but also for Archival - see $trigger_dt info)
			$ar = $this-> read($act_id);
			if(!$ar)
				return MVC_Core::$debug-> dump(sprintf("Action with Id: %d was not found. (Maybe it has already executed? Check Archive)", $act_id), __METHOD__, 'warning');

			// This only makes sense if existing action data is available
			if(!empty($operation) || !empty($action_data)) {
				// Instance the plugin to verify if the passed update data is correct
				$plugin = MVC_Core::factory_Plugin("action", $ar['executor']);
				if(!$plugin instanceof App_Plugin_Action)
					return MVC_Core::$debug-> dump(sprintf("Failed to instance Action execution plugin: %s", $ar['executor']), __METHOD__, 'error');

				$check = $plugin-> verify_Action($operation, $action_data);
				if(!$check)
					return MVC_Core::$debug-> dump(sprintf("Invalid action data for operation: %s in execution plugin: %s", $operation, $ar['executor']), __METHOD__, 'error');
			}
		}
		// Note, without read check, $trigger_dt and $operation cannot be updated

		$update_data = array();

		if(!empty($trigger_dt)) {
			// Special check, the updated Action trigger is in the past, the update will instead Archive the action (like Scan), with result_code = 0
			// - Other update parameters except $comment are ignored when $trigger_dt is set in the past, as the Action will be archived as it was, not as it would be after the update
			// - If $comment is present, it is placed in the Archive record
			$now = new DateTime();
			if($trigger_dt < $now) {
				MVC_Core::$debug-> dump(sprintf("Update Trigger DateTime %s is already in the past. Archiving action", $trigger_dt-> format("Y-m-d H:i:s")), __METHOD__, 'warning');

				if($read_check) { // Can only do this operation if $read_check is true
					$ar['trigger_dt'] = $trigger_dt-> format("Y-m-d H:i:s");
					if(!empty($comment))
						$ar['comment'] = (string)$comment;

					return $this-> archive($ar, 0, array('near'=> self::NEAR_DATE_IN_THE_PAST));
				} else
					return true;
			}
			// Else, valid $trigger_dt update
			$update_data['trigger_dt'] = $trigger_dt-> format("Y-m-d H:i:s");
		}

		if($read_check && isset($check)) {
			// Passing through check
			if(!empty($check['operation']))
				$update_data['operation'] = $check['operation'];
			if(!is_null($check['action']))
				$update_data['data_json'] = json_encode($check['action']);
		} elseif(!is_null($action_data)) {
			// Skip, direct update of action data
			$update_data['data_json'] = json_encode($action_data);
		}

		if(!empty($comment))
			$update_data['comment'] = (string)$comment;

		// update the table
		$q=QueryFactory::update()
		-> table(MVC_Core::$db-> tab['act'])
		-> values($update_data)
		-> where("`id` = ?", $act_id)
		-> limit(1);

		$r = MVC_Core::$db-> query($q);
		if(!$r)
			return MVC_Core::$debug-> dump("Error updating the action record", __METHOD__, 'error');

		return true;
	}

	/**
	 * Delete an action without executing it. Not moved into the archive, simply deleted.
	 * Usually used when the creator entity itself is deleted, but also when a specific action is no longer necessary
	 * @param int $act_id
	 */
	public function delete($act_id)
	{
		return MVC_Core::$db-> query(
			QueryFactory::delete()
			-> table(MVC_Core::$db-> tab['act'])
			-> where("`id` = ?", $act_id)
			-> limit(1)
		);
	}

	/**
	 * When executed, Actions are deleted from the primary table, but stored in the "archive" table along with the result of the operation
	 *
	 * @param array $action The source action data, as read by read(), or a row from scan() or get_List()
	 * @param int $result_code Just a quick code of the result. It should be positive for a successful action execution
	 * @param bool|array $result Result coming from the Executor plugin (gets placed in the "result_json")
	 * - Result might be null (simple success), false (failed action) - with a result code different than 0, or an array describing the outcome in detail
	 * @return int|boo -1 if archival was successful, false if failed (Why not true? Because some actions might return "true" when Action is executed, but -1 when it was archived instead)
	 */
	public function archive($action, $result_code = 0, $result = null)
	{
		// A bit of error checking before proceeding
		if(!is_array($action) || !isset($action['executor']))
			return MVC_Core::$debug-> dump("Invalid Action Record data for archival", __METHOD__, 'error');
		if(empty($action['executor']) || !in_array($action['executor'], self::$valid_executors))
			return MVC_Core::$debug-> dump(sprintf("Invalid Action execution plugin: %s for archival", $action['executor']), __METHOD__, 'error');

		$action['result_code'] = (int)$result_code;
		if(!empty($result))
			$action['result_json'] = json_encode($result);

		$q=QueryFactory::insert()
		-> table(MVC_Core::$db-> tab['aar']) // actions_archive
		-> values($action);

		$r = MVC_Core::$db-> query($q);
		if(!$r)
			return MVC_Core::$debug-> dump("Error achiving action ID: {$action['id']} ", __METHOD__, 'error');

		// Delete the action from the primary table so it won't be scanned and triggered at the next cycle
		$this-> delete($action['id']);

		return -1;
	}

// List methods

	/**
	 * Scans for actions that should be performed this cycle (have trigger_dt lower than current DateTime)
	 * -- Returns the data for found actions (which can be used in App_Model_Actions::execute)
	 *
	 * @param array Returns the list of action IDs that were detected (and triggered)
	 */
	public function scan()
	{
		$now = new DateTime();

		// Prepare the read query, with the only condition being "trigger_dt" lower than Now
		$q=QueryFactory::select()
		-> table(MVC_Core::$db-> tab['act']) // Complete readout
		-> where("`trigger_dt` < ?", $now-> format("Y-m-d H:i:s"))
		-> order("`trigger_dt` ASC") // Entries are processed in the order of their trigger moment
		-> limit(self::SCAN_LIMIT);

		$r = MVC_Core::$db-> query($q);
		if(!$r) {
			throw new Exception("Query error");
		}
		if(count($r) == 0) {
			return null; // Nothing to execute
		}

		$actions = array();
		foreach($r as $action) {
			$action['id'] = (int)$action['id'];
			$actions[$action['id']] = $action;
		}
		return $actions;
	}

	/**
	 * Executes an Action and returns the outcome
	 * -- May return information on what should happen with the action after execution (update, copy2archive, archive, delete)
	 * -- May also return a callback to be performed after action is processed
	 *
	 * @param array $action Passed through reference, execute may modify the action request it being updated
	 * @return array Result of operation, Action state info
	 */
	public function execute(&$action)
	{

		// Separate the action row into $meta and $action and pass them to the plugin
		$meta = array(
			'id'=> $action['id'],
			'create'=> new DateTime($action['create_dt']),
			'trigger'=> new DateTime($action['trigger_dt']),
		);
		if(!empty($action['org_id']))
			$meta['org_id'] = (int)$action['org_id'];
		if(!empty($action['creator_id']))
			$meta['creator_id'] = (int)$action['creator_id'];

		// Trigger is enabled, instance an executor and call an operation method - Note: The plugin instance is destroyed after the operation is performed
		$plugin = MVC_Core::factory_Plugin("action", $action['executor'], $meta, $this);

		// Plugin must be of type App_Plugin_Action
		if(!$plugin instanceof App_Plugin_Action) {
			MVC_Core::$debug-> dump(sprintf("Failed to instance Action execution plugin: %s", $action['executor']), __METHOD__, 'error');
			// Move the failed action to the archive and note that the plugin instancing failed (so it won't get picked up again at next cycle)
			$plugin_exception = MVC_Core::get_Plugin_Exception();
			return $this-> archive($action, self::RESULT_PLUGIN_INSTANCE_FAIL, $plugin_exception-> get_Error());
		}

		if(empty($action['operation']))
			$action['operation'] = "default"; // If Op is missing from the DB, just use a generic operation name (which may or may not exist in the plugins)

		if(method_exists($plugin, 'op_'.$action['operation'])) {
			try {
				MVC_Core::$db-> query("START TRANSACTION");
				$result = call_user_func(array($plugin, 'op_'.$action['operation']), !empty($action['data_json'])? json_decode($action['data_json'], true): null);
				// On plugin operation return, the action is placed in the archive with the result stored in it
				if(!is_array($result) || !isset($result['code']))
					$this-> archive($action, self::RESULT_PLUGIN_INVALID_RETURN, $result);
				else {
					// Exec success !
					$result_code = $result['code']; unset($result['code']);
					$this-> archive($action, $result_code, $result);
				}
				MVC_Core::$db-> query("COMMIT");
			} catch(Plugin_Exception $e) {
				// On Exception, cancel any operations which might have been done by the plugin, and archive the action instead with error
				MVC_Core::$db-> query("ROLLBACK");
				$this-> archive($action, self::RESULT_PLUGIN_OPERATION_FAIL, $e-> get_Error());
			}
		} else {
			// Move the failed action to the archive and note that the operation was not found (so it won't get picked up again at next cycle)
			$this-> archive($action, self::RESULT_PLUGIN_OPERATION_NOTFOUND);
		}

		unset($plugin);
	}

