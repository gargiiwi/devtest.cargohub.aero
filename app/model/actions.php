	/**
	 * Removes any Actions and action Archive records that were connected to the specific Creator element.
	 * - Used when the element is also deleted, to avoid orphaned data; (Does not verify if any actions do exist for the specified parameters)
	 *
	 * @param string $executor
	 * @param int $creator_id
	 * @return bool
	 */
	public function cleanup_Collection($executor, $creator_id)
	{
		if(empty($executor) || !in_array($executor, self::$valid_executors))
			return MVC_Core::$debug-> dump(sprintf("Invalid Action execution plugin: %s", $executor), __METHOD__, 'error');

		if(empty($creator_id))
			return MVC_Core::$debug-> dump("Creator ID must be specified", __METHOD__, 'error');

		MVC_Core::$db-> query(
			QueryFactory::delete()
			-> table(MVC_Core::$db-> tab['act'])
			-> where("`executor` = ?", $executor)
			-> where("`creator_id` = ?", $creator_id)
		);

		MVC_Core::$db-> query(
			QueryFactory::delete()
			-> table(MVC_Core::$db-> tab['aar'])
			-> where("`executor` = ?", $executor)
			-> where("`creator_id` = ?", $creator_id)
		);

		return true;
	}
