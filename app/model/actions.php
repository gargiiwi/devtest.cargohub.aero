/**
 * Base interface for Action Plugins
 * - Applies per executor type, with the plugin class matching the specified executor in the database
 *
 * @author Wavetrex Infinity <wavetrex@gmail.com>
 * @package CargoConnect
 * @subpackage DataModels
 * @version 2020.02.13
 */
interface App_Plugin_Action
{
	/**
	 * Verifies if the Operation and Action match the type of loaded plugin.
	 * Note: The plugin itself could modify these elements, and return the modified version in the array, based on it's internal logic.
	 *
	 * @param string $operation
	 * @param array $action Might be empty, when $operation sufficiently describes what the Action should do
	 * @param string $comment_append
	 * @return array|bool Returns an array containing at least the keys: 'operation', 'action', 'comment'
	 */
	public function verify_Action($operation, $action_data = null, $comment_append = null);
}