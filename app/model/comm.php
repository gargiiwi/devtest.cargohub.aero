	/**
	 * @deprecated Rethink the confirmation mechanism
	 * Attempts to confirm receipt of an e-mail containing a message.
	 * The parameters usually come from a link within the e-mail itself. If $recipient_email is present, it is checked against the "to_id" contact e-mail and it must match.
	 *
	 * The method verifies if the REMOTE_ADDR is different than the message stored "sender_id", and only confirms the message if the address is different.
	 * -- On succesful confirmation, it updates the message to "email_status" - confirmed, and sets the "confirm_ip"
	 * -- Once a message transmission has been confirmed, the status can no longer be changed and the IP addresses are locked.
	 *
	 * @param int $msg_id
	 * @param string $recipient_email
	 */
	public function confirm_Email_Message($msg_id, $recipient_email = null)
	{
		if(empty($msg_id))
			return false; // Error, no message ID?

		$msg = $this-> read($msg_id, array('meta', 'contacts'));
		if(!$msg)
			return false; // Error, message not found

		$ret = array(
			'msg_id'=> (int)$msg['id'],
			'msg_source'=> $msg['source'],
			'status'=> $msg['email_status'],
			'org_id'=> (int)$msg['org_id'],
			'cnv_id'=> (int)$msg['cnv_id'],
			'from_id'=> (int)$msg['from_id'],
			'to_id'=> !empty($msg['to_id'])? (int)$msg['to_id']: null,
			'to'=> $msg['to']
		);

		// Was the message actually sent?
		if($msg['email_status'] == 'failed') {
			$ret['message'] = "The e-mailing function has failed to transmit this message, so it was never sent.";
			return $ret;
		}

		if($msg['email_status'] == 'retry') {
			$ret['message'] = "This message was created on {$msg['dt']} but could not be sent immediately. It is currently in the RETRY queue.";
			return $ret;
		}

		if($msg['email_status'] == 'none' || empty($msg['sender_ip'])) {
			$ret['message'] = "This message was not yet sent out as an e-mail, there's nothing to do about it.";
			return $ret;
		}

		// Or maybe it was already confirmed...
		if($msg['email_status'] == 'confirmed' && !empty($msg['confirm_ip'])) {
			$ret['sender_ip'] = long2ip($msg['sender_ip']);
			$ret['confirm_ip'] = long2ip($msg['confirm_ip']);
			$ret['message'] = "The message was already confirmed on ".date("Y-m-d (H:i)", $msg['confirm_dt'])." from IP: {$ret['confirm_ip']}";
			return $ret;
		}

		// Finally, the message is ready to be confirmed. Check the same IP addresses.
		$current_ip_u = sprintf('%u', ip2long($_SERVER['REMOTE_ADDR']));

// 		if($msg['sender_ip'] == $current_ip_u) {
// 			$ret['sender_ip'] = $_SERVER['REMOTE_ADDR'];
// 			$ret['status'] = 'test';
// 			$ret['message'] = "Thank you for testing the delivery confirm link. It works! (The link it intended for the recipient, not for the sender).";
// 			return $ret;
// 		}

		// Different IP? Proceed with the confirmation.
		$ret['sender_ip'] = long2ip($msg['sender_ip']);
		$ret['confirm_ip'] = $_SERVER['REMOTE_ADDR'];
		$ret['confirm_ip_u'] = $current_ip_u;
		$ret['status'] = 'confirming';
		$ret['message'] = "The message sent to {$msg['to']['name']} ({$msg['to']['email']}) has been successfully confirmed !";

/* 		$this-> update($msg_id, array(
			'email_status'=> "confirmed",
			'confirm_ip'=> $current_ip_u,
			'confirm_dt'=> time()
		));
 */
		return $ret;
	}

	/**
	 * Constructs a message using a file found in /view/sysmsg and variables contained in $data, using Drytemplate
	 * - $data will get some information attached to it, from the configuration file {system.*} and current domain settings {html.*}, so they can be used in the template.
	 * - Use the next method "email_System_Message" to also send out that message as an e-mail, as by default this method only creates a database record.
	 *   (When sending a system message to an internal user, the user might choose not to receive an e-mail, and instead only read the messages inside the system)
	 *
	 * @param int $contact_id Contact ID which will receive the generated message
	 * @param string $template_file
	 * @param array $data Data for the template (and also contact data)
	 * @param string $custom_subject Allow overriding the automatically generated subject (or present in the $template_file itself) with a custom subject.
	 *
	 * @return int The system message ID
	 */
	public function create_System_Message($contact_id, $template_file, $data, $custom_subject = null)
	{
		if(empty(MVC_Core::$ss-> domain_CFG))
			return MVC_Core::$debug-> dump("The domain configuration is missing or invalid", __METHOD__, null, 'error');

		if(empty($contact_id))
			return MVC_Core::$debug-> dump("No contact ID specified for sending a system message", __METHOD__, null, 'error');

		// It is assumed that the data already contains the key "contact", having inside at least fields "name" and "email". If not, the contact is read (along with all it's data)
		if(!isset($data['contact']) || !isset($data['contact']['email']) || !isset($data['contact']['name'])) {
			$m_con = new App_Model_Contact();
			$data['contact'] = $m_con-> read($contact_id);
		}

		// Add the domain "html_settings" as "html", and also the domain name itself.
		$data['html'] = MVC_Core::$ss-> domain_CFG['html_settings'];
		$data['html']['domain'] = MVC_Core::$ss-> domain_CFG['domain'];

		// Add the stuff specified in the settings file, section "communication"
		if(isset(MVC_Core::$settings['communication']))
			$data['settings'] = MVC_Core::$settings['communication'];

		$CFG = new stdClass();
		$CFG-> paths = array('templates'=> array(
			ROOT. DS. 'app'. DS. 'view'. DS. 'sysmsg',
			ROOT. DS. 'app'. DS. 'view'
		));
		$drytpl = new Drytemplate($CFG);
		$content = $drytpl-> render_File($template_file, $data);

		if(empty($content))
			return false; // Error, nothing to send !

		// If not overwritten, the subject is retrieved from the template itself by using {#store:subject:<the subject>}, which can also use variables from the $data, or is generated automatically if no subject was provided (not very useful).
		if(!is_null($custom_subject))
			$subject = $custom_subject;
		elseif(isset($data['subject']))
			$subject = $data['subject'];
		else
			$subject = "Message from {$data['html']['title']} for {$data['contact']['email']}.";

		$msg_id = $this-> create("system", $content, $subject,
			array(
				'recipients'=> $contact_id
			));

		return $msg_id;
	}
        
