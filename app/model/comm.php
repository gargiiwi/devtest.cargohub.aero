	/** 
	 * Adds a message into the system
	 * -- note that for user to user messages, there must be two copies - One to the sender, one to the receiver
	 * -- special mass messages from administrators/managers will only keep one copy for the sender, while replicating it in many copies for the receivers
	 * -- messages that are used in communication with the outside will only have one copy
	 * -- system notification messages also only one single copy
	 *
	 * @param string $source What generated this message
	 * - system:	Usually system notifications, these messages are attached to a 1-message conversation record and cannot be replied - "system" conversation
	 * - sendmail:	Sending something as an e-mail (usually an issue, in which case this message is part of an issue-linked conversation). It could have other purposes as well
	 * - user:		A message generated by a system user, as a reply to a normal conversation (non issue-linked)
	 * - isspost:	This message was created as the result of posting an issue in the system. It may come from an user or from outside source - "issue" conversation
	 * - issreply:	Secondary message related to an issue conversation, might be a reply to the initial issue conversation, or any message in any secondary conversation
	 * - imap:		This message was recorded as the result of the system accessing an IMAP/POP3 server using PHP Imap library - It is allocated to the user or organization that owns the credentials for the imap/pop3 box
	 * - rss:		News post from a linked feed, allocated to the entity owning the link to the feed
	 * - broadcast:	A special message that is sent out by one user to multiple contacts which might be inside or outside the system (example: Mail-list) - "broadcast" conversation
	 * - draft:		An unfinished message which should only show up for the user creating it. The system autosaves these periodically while in the Compose/Reply interfaces
	 * - external:	Created by the use of a "conversation reply" form on non-issue conversations. This type of message isn't received by e-mail - "basic", "issue" or "broadcast" conversation
	 *
	 * @param string $content Must be shorter than ~64k In the internal version, it doesn't contain attachments (they are stored sepparately)
	 * @param string $subject The subject of the message (optional)
	 * @param array $msg Message data - various fields, described below:
	 * -- from_id:		Sender contact id
	 * @deprecated -- to_id:		Recipient contact id (or null if there is no specific recipient - isspost, pop3, rss, broadcast)
	 * -- recipients:	Optional: Support for multiple recipients within the same message (Necessary for E-mails) - These are all the Contact IDs (If missing, the "to_id" becomes part of the list)
	 * Formats:
	 * ~ List of ID's (CSV) or array of IDs - First one becomes "To", Everything else "Cc"
	 * ~ Array with keys: "to", "cc", "bcc" - Each member is either a CSV list or an array of contact IDs
	 * IMPORTANT: All contact records must exist before creating the message !
	 * -- cnv_id:		Conversation ID - Messages are linked to conversations. Can be null for system messages (non-linked to conversations)
	 * -- emotion:		An extension allowing an emoji to be displayed for a message viewed inside the software (Has no effect for e-mails)
	 * -- files:		List of "file" objects that are attached to this message ( TODO ) - Optional
	 * @return int|false The Insert ID of the new message
	 */
	public function create($source, $content, $subject = null, $msg = array())
	{
		if(!in_array($source, array("system", "user", "isspost", "issreply", "imap", "rss", "sendmail", "broadcast", "draft", "external")))
			return MVC_Core::$debug-> dump("Incorrect message source: $source", __METHOD__, null, 'error');

		// any key outside the correct fields is discarded (to avoid database errors)
		$fields = array('con_id', 'org_id', 'cnv_id', 'source', 'dt', 'from_id', 'to_id', 'email_status', 'error_status', 'sender_ip', 'recipients', 'emotion', 'count_files');
		foreach($msg as $field=> $value)
			if(!in_array($field, $fields))
				unset($msg[$field]);

		// Extra auto fields:
		// -- org_id: Id of the organization that is involved with this message (all messages sent from users in this organization will set this, or if a message is connected to an item that belongs to the organization)
		// -- dt: Date when this message was created
		// -- from_id: Always 0 when $source = "system"
		// -- recipient_distrib: Depends on the list of recipients and their types

		// since this is used mostly in ajax requests, do not allow the exception to be displayed.
		try {
			// Process message information before recording
			if(!isset($msg['dt']))
				$msg['dt'] = date("Y-m-d H:i:s"); // mysql datetime
			$msg['source'] = $source;
			if(is_string($subject))
				// cut subject if it exists, max length is 200 chars (looks weird in e-mail clients if bigger)
				$msg['subject'] = substr($subject, 0, 200);
			$msg['content'] = $content;

			// Analyse multi-recipients; 3 ways
			// - If there's just one recipient ( a number, that's the sole recipient of this message - Usually used by the system for direct notifications )
			// - First, just a list of ID's - 1st becomes "to", all the rest become "cc"
			// - Second, with very specific to, cc, bcc entries in an array
			if(is_numeric($msg['recipients'])) {
				$msg['recipients'] = (string)$msg['recipients'];
				$msg['recipient_distrib'] = "1,0,0"; // Only one "to", cc and bcc are empty
			} elseif(is_string($msg['recipients'])) {
				$recipient_count = count(explode(',', $msg['recipients']));
				$msg['recipient_distrib'] = "1,".($recipient_count-1).',0'; // 1 to, the rest cc, nothing to bcc
			} elseif(is_array($msg['recipients']) && isset($msg['recipients']['to'])) {
				// Customized distribution (new fancy control interface) - All ID's are in arrays (unlike the string version, in which they're already joined)
				$recipients_list = implode(',', $msg['recipients']['to']);
				$msg['recipient_distrib'] = "".count($msg['recipients']['to']);
				if(isset($msg['recipients']['cc'])) {
					$recipients_list.= ','.implode(',', $msg['recipients']['cc']);
					$msg['recipient_distrib'].= ','.count($msg['recipients']['cc']);
				} else
					$msg['recipient_distrib'].=',0';
				if(isset($msg['recipients']['bcc'])) {
					$recipients_list.= ','.implode(',', $msg['recipients']['bcc']);
					$msg['recipient_distrib'].= ','.count($msg['recipients']['bcc']);
				} else
					$msg['recipient_distrib'].=',0';
				$msg['recipients'] = $recipients_list; // Replace the 2-level array with the string
			} elseif(isset($msg['to_id'])) {
				// Legacy method or calling
				$msg['recipients'] = (string)$msg['to_id'];
				$msg['recipient_distrib'] = "1,0,0";
			} else
				return MVC_Core::$debug-> dump("Unrecognized or missing recipients information", __METHOD__, null, 'error');

			switch($source) {
				// Message sent by the system (generated by an event) to an user or as a notification to an external e-mail
				case 'system':
					// This message can't be replied, comes by default from "contact 0" (doesn't exist, defaults to the system e-mail)
					if(empty($msg['from_id']))
						$msg['from_id'] = 0;
					break;

				// Message sent from an user to another user inside the system (no e-mail was generated)
				case 'user':
					break;

				// Initial message that was generated by the posting of an issue from an external customer, or when creating the issue by a staff member
				// -- second step after creating this message would be to create a conversation from this message, and link the conversation to the issue
				case 'isspost':
					break;

				// Message that is a reply to an issue conversation - Currently not implemented
				case 'issreply':
					break;

				case 'imap':
					// Message that was generated by analising an external email box (imap, pop3)
					// (TODO: ??? - using PHP Imap library)

					break;
				case 'rss':
					// Message that was generated by updating a RSS Feed (all new entries become messages)
					// (TODO: ???)

					break;
				case 'sendmail':
					// Sending data from the system as an e-mail (Right now used only by the "Send by mail" function)
					// (TODO: ???)

					break;
				case 'broadcast':
					// Special message which has a single copy, one sender and multiple recipients which are specified in a "conversation" record

					// (TODO: ???)
					break;
			}

			// Emotions (Not used yet)
			if(isset($msg['emotion'])) {
				$emotions = array('evilgrin','grin','happy','smile','surprised','tongue','unhappy','waii','wink');
				if(!in_array($msg['emotion'], $emotions))
					unset($msg['emotion']);
			}

			// Insert the message into the system
			$q=QueryFactory::insert()
			-> table(MVC_Core::$db-> tab['msg'])
			-> values($msg);

			$r = MVC_Core::$db-> query($q);
			if(!$r)
				return MVC_Core::$debug-> dump("Unable to create the message record. Some parameters might be incorrect", __METHOD__, null, 'error');

			$iid = MVC_Core::$db-> insert_id;

			// If there is a "from_id" value, which means that a contact created this (and not system), increase the "sent messages" counter for that contact
			if(isset($msg['from_id']) && $msg['from_id']> 0) {
				$q=QueryFactory::update()
				-> table(MVC_Core::$db-> tab['ctx'])
				-> values(array(
					'count_msgs'=> "`count_msgs`+1"
				), null, true)
				-> where("`id` = ?", $msg['from_id']);

				MVC_Core::$db-> query($q);
			}

			return $iid;
		} catch(Exception $e) {
			return false;
		}
	}

	/**
	 * Reads a single message, and various data associated with it
	 *
	 * @param id $msg_id The message ID (primary key)
	 * @param array $wtr List of what kind of data to read from the message ("meta", "content", "sender", "recipients", "organization", "files", "conversation", "contacts" ) // @deprecated "contacts"
	 */
	public function read($msg_id, $wtr = array("meta"))
	{
		$q=QueryFactory::select()
		-> where("`msg`.`id` = ?", $msg_id)
		-> limit(1);

		$wtr = self::wtr_Helper($wtr);

		if(in_array('meta', $wtr) && in_array('content', $wtr))
			$q-> table(array(MVC_Core::$db-> tab['msg'],'msg')); // all fields in the primary table
		elseif(in_array('meta', $wtr))
			$q-> table(array(MVC_Core::$db-> tab['msg'],'msg'), 'id,con_id,org_id,cnv_id,source,dt,from_id,email_status,error_status,sender_ip,recipients,recipient_distrib,emotion,subject,unread,count_files'); // everything except the content (as it's the heaviest by far)
		else
			$q-> table(array(MVC_Core::$db-> tab['msg'],'msg'), 'id,source'); // just id, message source from the primary table (test mode)


		if(in_array('sender', $wtr))
			$q-> table(array(MVC_Core::$db-> tab['ctx'],'ctx_from'), QueryFactory::autoalias_Add_Prefix("id,org_id,name,email,user_id", '_ctxf_'), 'left', '`msg`.from_id = `ctx_from`.id');

		// @deprecated (Read From/To, just two contacts ) - New method supports 1 sender, any number of recipients (recipients/recipient_distrib) fields
		if(in_array('contacts', $wtr)) { // TODO: Replace with 'sender', and adjust all code reading messages
			// Only the sender - because there could be several recipients, and they need to be read separately ( for each message )
			$q-> table(array(MVC_Core::$db-> tab['ctx'],'ctx_from'), QueryFactory::autoalias_Add_Prefix("id,org_id,name,email,user_id", '_ctxf_'), 'left', '`msg`.from_id = `ctx_from`.id');
//			$q-> table(array(MVC_Core::$db-> tab['ctx'],'ctx_to'), QueryFactory::autoalias_Add_Prefix("id,name,email,user_id", '_ctxt_'), 'left', '`msg`.to_id = `ctx_to`.id');
		}

		if(in_array('organization', $wtr))
			$q-> table(array(MVC_Core::$db-> tab['org'],'org'), QueryFactory::autoalias_Add_Prefix("type_id,name", '_org_'), 'left', '`msg`.org_id = `org`.id');
		// Conversation in which this message is part of (used for linking replies)
		if(in_array('conversation', $wtr))
			$q-> table(array(MVC_Core::$db-> tab['cnv'],'cnv'), QueryFactory::autoalias_Add_Prefix("type,visibility,link_id,contact_ids,access_key,count_msgs,last_msg_time,description", '_cnv_'), 'left', '`msg`.cnv_id = `cnv`.id');

		$r = MVC_Core::$db-> query($q);

		if(!$r || count($r)==0)
			return MVC_Core::$debug-> dump("Message {$msg_id} not found", __METHOD__, null, "error");

		$r-> split_by_prefixes = array(
			// extra tables
			'from'=> "_ctxf_",
			'to'=> "_ctxt_",	// @Deprecated
			'organization'=> "_org_",
			'conversation'=> "_cnv_"
		);

		$msg = $r-> current();

		// Read the recipient contacts for the message, then distribute into To/Cc/Bcc accordingly
		if(in_array('recipients', $wtr) && !empty($msg['recipients'])) {
			$msg['recipients_ids'] = explode(',', $msg['recipients']);

			// Uses: "Contact" model
			$m_con = new App_Model_Contact();
			// Read all contacts in the list in the order specified in the idlist
			$recipients = $m_con-> get_List(null, $msg['recipients_ids'], 'idlist', array('allstates'), "FIELD(`id`, {$msg['recipients']})", 0);
			// Distribute according to "recipient_distrib"
			list($c_to, $c_cc, $c_bcc) = explode(',', $msg['recipient_distrib']);
			$msg['recipients'] = array(
				'to'=> array_splice($recipients, 0, $c_to, null)
			);
			$msg['recipients']['cc'] = array_splice($recipients, 0, $c_cc, null);
			$msg['recipients']['bcc'] = $recipients; // What's left
			unset($msg['recipient_distrib']);
		}

		// TODO: The associated files data is read a secondary query
		if(in_array('files', $wtr) && !empty($msg['count_files'])) {

			// Uses: "File" model
			$m_file = new App_Model_File();
			$r_files = $m_file-> get_List('message', $msg['id'], array('file', 'extra'));
			if($r_files === false)
				MVC_Core::$debug-> dump("The attached message files could not be accessed", __METHOD__, null, "warning");
			else {
				// Post process file list
				$msg['files'] = array();
				foreach($r_files as $file) {
					$file['id'] = (int)$file['id'];
					$file['size'] = (int)$file['size'];
					$msg['files'][] = $file;
				}
			}
		}

		// TODO: Process the conversation metadata (not sure if needed anymore)
		if(in_array('conversation', $wtr)) {
		}

		return $msg;
	}

	/**
	 * Updates certain meta values for a stored message
	 * - Message content or subject cannot be changed, neither is conversation ID or "emotion" (internal messages only)
	 *
	 * @param int $msg_id
	 * @param array $msg_update
	 */
	public function update($msg_id, $msg_update)
	{
		// any key outside the correct fields is discarded (to avoid database errors)
		$fields = array('org_id', 'source', 'from_id', 'to_id', 'email_status', 'error_status', 'sender_ip', 'confirm_ip', 'confirm_dt', 'recipients', 'recipient_distrib', 'count_files');
		foreach($msg_update as $field=> $value) {
			if(!in_array($field, $fields))
				unset($msg_update[$field]);
		}

		// FIXME: This doesn't analyze "recipients" to build "recipient_distrib"; Data should be correct

		if(isset($msg_update['source']) && !in_array($msg_update['source'], array("system", "user", "isspost", "issreply", "imap", "rss", "sendmail", "broadcast", "draft", "external")))
			return false; // Error, invalid message soruce

		$q=QueryFactory::update()
		-> table(MVC_Core::$db-> tab['msg'])
		-> where("`id` = ?", $msg_id)
		-> values($msg_update);

		return MVC_Core::$db-> query($q);
	}

	/**
	 * Deletes a message from the database
	 *
	 * @param int $msg_id
	 * @param array $flags Contains a list of flags to indicate what other data is removed (Defaults to none)
	 * - "files" - The method deletes all the files that are associated with this message
	 * - "conversation" - Deletes all the messages that are replies to this message (in case the message is the conversation starter: source = "user", id = connect_id )
	 */
	public function delete($msg_id, $flags = array())
	{
		// since this is used in ajax requests, do not allow the exception to be displayed.
		try {
			// first, check if the message id actually exist, if not, return an error
			$q=QueryFactory::select()
			-> table(MVC_Core::$db-> tab['msg'], 'id,cnv_id,source,count_files')
			-> where("`id` = ?", $msg_id);

			$r = MVC_Core::$db-> query($q);

 			if($r && count($r)==1) {
 				$msg = $r-> current();

 				// depending on what kind of message it is, do further processing ??
 				switch($msg['source']) {
 					case 'system':
 						break;
 					case 'user':
 						break;
 					case 'isspost':
 					case 'issreply':
 						break;
 					case 'imap':
 					case 'rss':
 					case 'sendmail':
 					case 'broadcast':
 					case 'draft':
 					case 'external':
 						break;
 				}

 				// finally, remove the message record itself from the db
 				$q=QueryFactory::delete()
 				-> table(MVC_Core::$db-> tab['msg'])
				-> where("`id` = ?", $msg_id);

 				$r = MVC_Core::$db-> query($q);

 				return true;
 			}
 			return false; // not found?
		} catch(Exception $e) {
			return false;
		}
	}

	/**
	 * Helper that filters items in cleanup_Collection, to read all messages related to one entity
	 *
	 * @param QueryFactory $q
	 * @param array $params
	 */
	protected function filter_Entity_IDs(QueryFactory &$q, $params)
	{
		// params[0] - entity, params[1] - the ID
		$q-> where("`{$params[0]}_id` = ?", $params[1]);
	}

	/**
	 * Deletes all messages connected to an entity (either an user - field: owner_id, or an item - field: connect_id, or the organization - field: org_id)
	 * -- usually this operation is done when the entity is removed from the system, but can also be triggered in other occasions
	 * TODO: Review this method, it no longer works with the conversation model !
	 *
	 * @param string $entity ( owner, org, connect )
	 * @param int $entity_id
	 * @param bool $update_counts Perform container and user updating, or skip it for when those will be deleted as well.
	 */
	public function cleanup_Collection($entity, $entity_id, $update_counts = true)
	{
		try {
			// first, read the list of messages connected to the entity, using the method read_Messages (to find out other data related to the messages)
			$r = $this-> get_List("meta", array($this, "filter_Entity_IDs"), array($entity, $entity_id), null, false); // read all, no limit in size

			if($r && count($r)>0) {

				if($update_counts) {
					$con_count_decrease = array(); // to calculate the reduction of container message counts, for the list of self-owned messages
					foreach($r as $msg) {
						if(!is_null($msg['con_id'])) {
							if(!isset($con_count_decrease[$msg['con_id']]))
								$con_count_decrease[$msg['con_id']] = 1;
							else
								$con_count_decrease[$msg['con_id']]++;
						}

						// TODO: Maybe a log of what messages have been deleted?
					}

					// update the containers with the new count_msgs numbers.
					foreach($con_count_decrease as $con_id=> $count_decrease) {
						$q= QueryFactory::update()
						-> table(MVC_Core::$db-> tab['lab'], 'count_el')
						-> values(array("`count_el`"=> "`count_el` - {$count_decrease}"), null, true)
						-> where("`id` = ?", $con_id);

						MVC_Core::$db-> query($q);
					}

					// update the entity and set it's message count to 0 (even if that record will be deleted after)
					$tables = array(
						'owner'=> 'usr',
						'org'=> 'org',
						'connect'=> 'iss'	// TODO: Make this flexible? - In order to have connects to other types of items, not just issues
					);

					$q=QueryFactory::update()
					-> table(MVC_Core::$db-> tab[$tables[$entity]])
					-> values(array(
						'count_msgs'=> 0
					))
					-> where("`id` = ?", $entity_id);

					MVC_Core::$db-> query($q);
				}

 				// remove all the messages connected to this entity
 				$q=QueryFactory::delete()
 				-> table(MVC_Core::$db-> tab['msg'])
 				-> where("`{$entity}_id` = ?", $entity_id);

 				MVC_Core::$db-> query($q);
		 		return true;
			}
			if($r == false)
				return false; // error?
			else
				return true; // success, but no messages were actually deleted
		} catch(Exception $e) {
			return false;
		}
	}

