	/**
	 * Reads a list of messages using various criteria which can be accessed in the communication table, using a callback that can add conditions to the QueryFactory object
	 * -- Supports paging
	 *
	 * @param array $wtr Indicates what information to read ( "meta", "content", "sender" )
	 * @param Callback $qfo_filter If no callback specified, it simply reads any messages in the system (not recommended !), or only first 100 if the limit is still in place
	 * @param array $filter_params
	 * @param string $order_by Which field to be used for ordering
	 * @param int $count_rows Paging Size
	 * @param int $start_row Paging Start
	 * @return MVC_Database_Result This method doesn't perform post-processing, due to possible large size of involved messages; Instead, use self::post_Process_Message() for that purpose
	 */
	public function get_List($wtr = array('meta'), $qfo_filter = null, $filter_params = array(), $order_by = null, $count_rows = 100, $start_row = 0, $calc_found_rows = false)
	{
		$q = $this-> get_List_QueryFactory_Helper($qfo_filter, $filter_params, is_null($order_by)? "`msg`.dt ASC": $order_by, $count_rows, $start_row, $calc_found_rows);
		if(empty($q))
			return false; // Error, filter failed

		// What to read?
		$wtr = self::wtr_Helper($wtr);

		if(in_array('meta', $wtr) && in_array('content', $wtr))
			// all fields in the primary table (including message content - might be long !)
			$q-> table(MVC_Core::$db-> table('msg'));
		elseif(in_array('meta', $wtr))
			// everything except the content (as it's the heaviest by far)
			$q-> table(MVC_Core::$db-> table('msg'), 'id,con_id,org_id,cnv_id,source,dt,from_id,email_status,error_status,recipients,recipient_distrib,emotion,subject,count_files');
			// Deprecated fields - Remove after conversion is complete !:
			//   owner_id - The user who received this "system" or "user" message
			//   con_id - User container id, which has become a  "label", and connected to the conversation, not the message
			//   connect_id - The original link between messages and issues
		else
			// read just id and a few other fields (test mode)
			$q-> table(MVC_Core::$db-> table('msg'), 'id,source,from_id');

		// Read some information about the conversation to which this message belongs (if it exists, otherwise null's)
		if(in_array('convo', $wtr)) {
			$q-> table(MVC_Core::$db-> table('cnv'), QueryFactory::autoalias_Add_Prefix("type,visibility,link_id,org_id,access_key", '_cnv_'), 'left', '`cnv`.id = `msg`.cnv_id');
		}

		if(in_array('record_link', $wtr)) {
			// Link main record metadata to get TrackID and a few other parameters on messages belonging to conversations linked to records. Very special use case.
			$q-> table(MVC_Core::$db-> table('iss'), QueryFactory::autoalias_Add_Prefix("track,type_id,group_id", '_iss_'), 'left', '`iss`.id = `cnv`.link_id');
		}

		if(in_array('sender', $wtr))
			// The sender of this message, if he/she exists
			$q-> table(MVC_Core::$db-> table('ctx', true, 'send'), QueryFactory::autoalias_Add_Prefix("name,email,org_id,user_id", '_send_'), 'left', '`msg`.from_id = `send`.id');
/* @deprecated
		if(in_array('receiver', $wtr))
			// The sender of this message, if he/she exists
			$q-> table(array(MVC_Core::$db-> tab['ctx'],'recv'), QueryFactory::autoalias_Add_Prefix("name,email,org_id,user_id", '_recv_'), 'left', '`msg`.to_id = `recv`.id');
*/

		$r = MVC_Core::$db-> query($q);
