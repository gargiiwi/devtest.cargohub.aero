	 *
	 * @param $msg_id The ID of the message that will be sent out as an E-mail
	 * @param array|string(json) $options Sending options: (if other values are encountered they will be ignored)
	 * - "signature"	Def: FALSE - Append the logged in user's signature to the message (only if message is sent by an user)
	 * - "attachments"	Def: TRUE - Use the already attached files as either E-mail attachments or "cloud" stored links. If false, the linked attachments are ignored.
	 *					Still, attachments can be sent by specifying them in the $attachments parameter
	 * - "cloud"		Def: FALSE - Instead of sending attachments with the E-mail itself, just link them in the message as "cloud_files" ( to be downloaded from the server ) - Makes the message tiny instead of huge
	 * - "cloud_zip"	Def: FALSE - When there's more than one attachment to the E-mail and "cloud" is being used, it creates a zip package out of them and sends the link to that one instead
	 * - "status"		Def: TRUE - Update the message status if the sending was successful. This option by default is TRUE, so the option is only to disable the status update
	 * - "extret"		Def: FALSE - Extended return on success. Instead of [true], it returns an array with information (recipient emails in an array)
	 * @param array $xattachments If an array, read those external files and attach them (possibly adding to the linked ones, if they exist and are enabled). Format is array(name=> realpath, ...)
	 *					Note: These files are ALWAYS attached to the mail, as true attachments, and increase the size of the E-mail. Careful !
	 * @param array $xembeds If an array, these are file paths relative to root which are embedded with the e-mail itself (usually small images/logos)
	 */
	public function msg_Mailer($msg_id, $options = null, $xattachments = null, $xembeds = null)
	{
	
	
		if(empty($msg_id))
			return MVC_Core::$debug-> dump("No message ID present", __METHOD__, null, 'error');

		// Prepare options array
		if(empty($options))
			$options = array();
		elseif(is_string($options))
			$options = json_decode($options, true);
		if(!isset($options['signature']))
			$options['signature'] = false;
		if(!isset($options['attachments']))
			$options['attachments'] = true;
		if(!isset($options['cloud']))
			$options['cloud'] = false;
		if(!isset($options['status']))
			$options['status'] = true;
		if(!isset($options['extret']))
			$options['extret'] = false;

		if(!empty($options['extret']))
			$ret = array();
		else
			$ret = true;

		// Read the stored message optionally the linked attachments
		$wtr = array('meta', 'content', 'sender', 'recipients', 'conversation');
		if($options['attachments'] === true)
			$wtr[] = "files";
		$msg = $this-> read($msg_id, $wtr);

		// If a conversation exists and is linked to the E-mail, make sure an external access key is defined
		if($msg['cnv_id'] && is_array($msg['conversation']) && empty($msg['conversation']['access_key'])) {
			$msg['conversation']['access_key'] = sha1(microtime(1) . uniqid());

			// Update (set) conversation access key
			$m_cnv = new App_Model_Conversation();
			$m_cnv-> update($msg['cnv_id'], array(
				'access_key'=> $msg['conversation']['access_key']
			));
		}

		// Setup content of the e-mail
		$tpldata = array(
			'domain'=> MVC_Core::$ss-> domain_CFG['domain'],
			'subject'=> $msg['subject'],
			'contents'=> $msg['content'], // TODO: rename the database field into "contents" and adjust the code which is using it
			'prologue'=> false,	// Prologue is not implemented ( could be company header/presentation ) - Should be able to use one of the $embeds for header purposes
			'epilogue'=> true,	// Epilogue is currently "Powered by Cargohub" ( should be able to change by using one of the $embeds )
			// Information about the message itself
			'id'=> $msg['id'],
			'dt'=> $msg['dt']
		);

		// User signature is appended if needed
		if(!empty($options['signature']) && !empty(MVC_Core::$ss-> user))
			$tpldata['signature'] = MVC_Core::$ss-> user['signature'];

		// Conversation related info ( for responding )
		if(isset($msg['conversation'])) {
			$tpldata['convo'] = array(
				'key'=> $msg['conversation']['access_key'],
				'description'=> $msg['conversation']['description']
			);
		}

		// Handling attachments: Message linked / External, and the method of delivery: Attached / Cloud (individual) / Cloud (package - Zip)
		if(!empty($options['attachments']) && !empty($options['cloud'])) {
			// Zip the Cloud attachments before assembling ?
			if(!empty($options['cloud_zip'])) {

			} else {
				// Nope, plain links
				$tpldata['cloud_files'] = $msg['files'];
			}
		}

		// Initialize DryTemplate and render the main HTML will will become the body of the sent E-mail
		$CFG = new stdClass();
		$CFG-> paths = array('templates'=> array(
			ROOT. DS. 'app'. DS. 'view'
		));
		$drytpl = new Drytemplate($CFG);
		$message = $drytpl-> render_File("email". DS. "comm_sendmail.html", $tpldata);

		// Use phpMailer to send the message via the asked method: mail() or smtp(), using the authentication methods present in the "servers" table record
		$mailer = new PHPMailer();
		$mailer-> CharSet = "UTF-8";

		if(!empty($msg['recipients'])) {
			// New method, recipients are in the "recipients" array, already distributed in To/Cc/Bcc
			foreach($msg['recipients']['to'] as $contact) {
				$mailer-> addAddress($contact['email'], $contact['name']);
				if(!empty($options['extret'])) {
					if(empty($ret['to']))
						$ret['to'] = array();
					$ret['to'][] = $contact['email'];
				}
			}
			if(!empty($msg['recipients']['cc']))
				foreach($msg['recipients']['cc'] as $contact) {
					$mailer-> addCC($contact['email'], $contact['name']);
					if(!empty($options['extret'])) {
						if(empty($ret['cc']))
							$ret['cc'] = array();
						$ret['cc'][] = $contact['email'];
					}
				}
			if(!empty($msg['recipients']['bcc']))
				foreach($msg['recipients']['bcc'] as $contact)
					$mailer-> addBCC($contact['email'], $contact['name']);
		} else
			// Problem - No recipients !
			return MVC_Core::$debug-> dump("The recipient list is empty. Can't send the e-mail", __METHOD__, null, 'error');

		// System is the sender, but the name of the contact that created the message is used. Reply-To added for smart e-mail clients that know to reply directly to the sender contact.
		// Unfortunately, this doesn't always work... Perhaps by using SMTP with the actual user's mail system it would send directly from the proper address.
		$system_email = str_replace("{domain}", $tpldata['domain'], MVC_Core::$settings['communication']['system_email']);
		$system_name = MVC_Core::$settings['communication']['system_name'];
		if(!isset($msg['from']['name']))
			$msg['from']['name'] = $system_name;
		if(!isset($msg['from']['email']))
			$msg['from']['email'] = MVC_Core::$settings['communication']['support_email']; // Redirect replies which do not have a sender to the support account (System Messages)

		// Prepare connection according to the stored server info and the sender contact ID. If no special settings are saved, then mail() will be used automatically
		$m_con = new App_Model_Contact(); // FIXME: This is a bit redundant, as a contact model object is most likely already in memory at this point
		$send_mtd = $m_con-> server_PrepConnection($msg['from']['id'], $mailer);

		$mailer-> MessageID = "<CargoHub.{$msg_id}@{$tpldata['domain']}>";

		if(!empty($options['extret'])) {
			$ret['from'] = $msg['from']['email'];
		}

		// When using mail(), send as $system_mail, but with the E-mail address of the sender included
		// Note: If using Sender and setFrom as different E-mails, fraud detection will be triggered on many servers (it sucks, but nothing we can do about it)
		switch($send_mtd) {
			// With SMTP, the sender contact is the actual sender
			case 'smtp':
				$mailer-> setFrom($msg['from']['email'], $msg['from']['name']);
				break;
			case 'spf':
				$mailer-> Sender = $msg['from']['email'];
				$mailer-> setFrom($msg['from']['email'], $msg['from']['name']);
				$mailer-> addReplyTo($msg['from']['email'], $msg['from']['name']);
				break;
			// The good old default (no-reply@...)
			case 'local':
			default:
				if($msg['from']['email'] == $system_email)
					$from_name = "Cargohub Connect";
				else
					$from_name = $msg['from']['name'].' | '.str_replace('@','[at]',$msg['from']['email']). ' | ';

				$mailer-> Sender = $system_email;
				$mailer-> setFrom($system_email, $from_name);
				$mailer-> addReplyTo($msg['from']['email'], $msg['from']['name']);
				break;
		}

		//Set the subject line
		$mailer-> Subject = $tpldata['subject'];

		$mailer-> msgHTML($message);
