	 *
	 * Sends an existing database-recorded message via E-mail to the intended recipient contact.
	 * Reads the message record and associated contacts in order to determine the e-mail address, additional recipients
	 *
	 * Note: Normally, this method should only be called ONCE when a message is created, but it may be called additional times in case for some reason e-mail could not be delivered
	 * (TODO: A way to determine if an e-mail has been actually delivered to the primary recipient?)
	 *
	 * TEMP: This method should work in both "compatibility" mode, in which the recipient information is taken from the "To" contact id,
	 * -- but also in modern mode, in which there's a list of recipients in the fields "recipients", seppareted into To/Cc/Bcc by using the numbers in "recipient_distrib.
	 * -- "to_id" field takes precedence, but if empty the modern method takes over
	 *
	 * @param int $msg_id
	 * @param array|string $recipients List of contact ID's or e-mail addresses (strings) that will also receive the message. The extra list becomes the set of CC entries in the sent e-mail.
	 * ( This is only used for the old method From/To - Unfortunately said recipients are NOT recorded; New method is using the list of recipients stored with the message )
	 * @param string $extra_styles Optional path (which can be included by the template system) containing a css file for the sent out e-mail.
	 * @param bool $update_status Updates the "email_status" of the message to "sent" or "smtpsent", if sending was successful.
	 * @param bool $standalone If true, no link to a conversation is created, as this message is standalone (And usually sent by the system).
	 * @param array $attachments If "true", attempt to read already connected files and send them as attachments; If an array, read those external files and attach them (ignore linked); If empty, no attachments will be sent.
	 * @param array $embeds If an array, these are file paths relative to root which are embedded with the e-mail itself (usually small images)
	 * @param array $options Sending options: (if other values are encountered they will be ignored)
	 * - "signature"	Append the logged in user's signature to the message
	 * - "cloud"		Instead of sending attachments with the E-mail itself, just link them in the message as "cloud_files" ( to be downloaded from the server ) - Makes the message tiny instead of huge
	 * - "extret"		Extended return on success. Instead of [true], it returns an array with information (recipient emails in an array)
	 * @return bool|array
	 */
	public function email_Message($msg_id, $recipients = null, $extra_styles = null, $update_status = true, $standalone = false, $attachments = null, $embeds = null, $options = null)
	{
		if(empty($msg_id))
			return MVC_Core::$debug-> dump("No message ID present", __METHOD__, null, 'error');

		$wtr = array('meta', 'content', 'sender', 'recipients');
		if(!$standalone)
			$wtr[] = "conversation";
		if($attachments === true)
			$wtr[] = "files";
		$msg = $this-> read($msg_id, $wtr);

		// Do not allow sending e-mails from empty messages. (Even if they might be necessary for the system itself)
/*		if(!$msg || empty($msg['content']))
			return MVC_Core::$debug-> dump("The message {$msg_id} has no content. Cannot send empty E-mail", __METHOD__, null, 'error');*/

		if(!empty($options['extret']))
			$ret = array();
		else
			$ret = true;

		// Check if the conversation has an external-use key. It means it's ready to be viewed/replied from outside. If not, create the key now and update the conversation record
		if(!$standalone)
			if(empty($msg['conversation']['access_key'])) {
				$msg['conversation']['access_key'] = sha1(microtime(1) . uniqid());

				// Update (set) conversation access key
				$m_cnv = new App_Model_Conversation();
				$m_cnv-> update($msg['cnv_id'], array(
					'access_key'=> $msg['conversation']['access_key']
				));
			}

		// Setup content of the e-mail
		$tpldata = array(
			'domain'=> MVC_Core::$ss-> domain_CFG['domain'],
			'subject'=> $msg['subject'],
			'prologue'=> $standalone? false: ($msg['email_status'] != 'confirmed'),
			'epilogue'=> true,
			// Information about the message itself
			'id'=> $msg['id'],
			'dt'=> $msg['dt']
		);

		// TODO: A way to process content and add styles dynamically (by replacing ... class="someclass" ... with style="what was in that class"); This is not working properly (getting filtered by Gmail, Outlook, etc.)
		if(!empty($extra_styles))
			$tpldata['styles'] = $extra_styles;

		// Conversation related info ( for responding ); Not sure if used right now...
		if(!$standalone)
			$tpldata['convo'] = array(
				'key'=> $msg['conversation']['access_key'],
				'description'=> $msg['conversation']['description']
			);

		// Body of the message; Should contain everything, including embedded styles: <tag style="...."> text </tag>
		$tpldata['contents'] = $msg['content'];

		// User signature is appended if needed
		if(!empty($options['signature']) && !empty(MVC_Core::$ss-> user))
			$tpldata['signature'] = MVC_Core::$ss-> user['signature'];

		// Linked attachments or arbitrary list of files to be attached?
		if($attachments === true && !empty($msg['files'])) {
			// Attach the linked files
			$attachments = $msg['files'];

		} elseif(!is_array($attachments) || count($attachments)==0)
			$attachments = null;

		if(!empty($options['cloud'])) {
			// Cloud option is set - Instead of creating real attachmenets, just provide links to the downloadable files (by using their hashes)
			$tpldata['cloud_files'] = $attachments;
		}

		// Initialize DryTemplate
		$CFG = new stdClass();
		$CFG-> paths = array('templates'=> array(
			ROOT. DS. 'app'. DS. 'view'
		));
		$drytpl = new Drytemplate($CFG);
		$message = $drytpl-> render_File("email". DS. "comm_sendmail.html", $tpldata);

		// Initialize MimeMail library and add contacts: recipient(s), sender, reply-to
		$mm = new MimeMail();

		if(!empty($msg['to_id'])) {
			// Old method - one stored recipient + extras
			$mm-> add_Contact($msg['to']['email'], "To", $msg['to']['name']);
			if(isset($recipients)) {
				if(is_string($recipients))
					$recipients = explode(",", $recipients);
				else {
					// recipients is an array, it's items might be numeric (contact ID's) or E-mail addresses (or combination of E-mail address and Name in the format: Name <E-mail>)
					$cc_contact_ids = array();
					foreach($recipients as $contact) {
						if(is_numeric($contact))
							$cc_contact_ids = (int)$contact;
						elseif(is_array($contact))
							$mm-> add_Contact($contact['email'], null, $contact['name']);
						elseif(is_string($contact))
							$mm-> add_Contact($contact);
					}
					// Is there at least one contact ID in the array ? If so, read those contacts.
					if(count($cc_contact_ids)>0) {
						$m_con = new App_Model_Contact();
						$cc_contacts = $m_con-> get_List(null, $cc_contact_ids, "idlist", array(), "FIELD(`id`, ".implode($cc_contact_ids).")");
						if($cc_contacts && count($cc_contacts)>0)
							foreach($cc_contacts as $contact)
								$mm-> add_Contact($contact['email'], null, $contact['name']);
					}
				}
			}
		} elseif(!empty($msg['recipients'])) {
			// New method, recipients are in the "recipients" array, already distributed in To/Cc/Bcc
			foreach($msg['recipients']['to'] as $contact) {
				$mm-> add_Contact($contact['email'], "To", $contact['name']);
				if(!empty($options['extret'])) {
					if(empty($ret['to']))
						$ret['to'] = array();
					$ret['to'][] = $contact['email'];
				}
			} if(!empty($msg['recipients']['cc']))
				foreach($msg['recipients']['cc'] as $contact) {
					if(!empty($options['extret'])) {
						if(empty($ret['cc']))
							$ret['cc'] = array();
						$ret['cc'][] = $contact['email'];
					}
					$mm-> add_Contact($contact['email'], "Cc", $contact['name']);
				}
			// Bcc's are used for sending, but not shown in ext.ret.
			if(!empty($msg['recipients']['bcc']))
				foreach($msg['recipients']['bcc'] as $contact)
					$mm-> add_Contact($contact['email'], "Bcc", $contact['name']);
		} else
			// Problem - No recipients !
			return MVC_Core::$debug-> dump("The recipient list is empty. Can't send the e-mail", __METHOD__, null, 'error');

		// System is the sender, but the name of the contact that created the message is used. Reply-To added for smart e-mail clients that know to reply directly to the sender contact.
		// Unfortunately, this doesn't always work... Perhaps by using SMTP with the actual user's mail system it would send directly from the proper address.
		$system_email = str_replace("{domain}", $tpldata['domain'], MVC_Core::$settings['communication']['system_email']);
		$system_name = MVC_Core::$settings['communication']['system_name'];
		if(!isset($msg['from']['name']))
			$msg['from']['name'] = $system_name;
		if(!isset($msg['from']['email']))
			$msg['from']['email'] = $system_email; // MVC_Core::$settings['communication']['support_email']; // Redirect replies which do not have a sender to the support account (System Messages)

		if($msg['from']['email'] == $system_email)
			$from_name = "Cargohub Connect";
		else
			$from_name = $msg['from']['name'].' | '.str_replace('@','[at]',$msg['from']['email']). ' | ';

		if(!empty($options['extret'])) {
			$ret['from'] = $msg['from']['email'];
		}

		$mm
		-> add_Contact($system_email, "From", $from_name)
		-> add_Contact($msg['from']['email'], "Reply-To", $msg['from']['name'])
		-> set_Subject($tpldata['subject'])
		-> set_Header("Message-ID", "<CargoHub.{$msg_id}@{$tpldata['domain']}>")
// 		-> set_Header("Sender", $system_email)
		-> set_textHTML($message, true) // , true also generate text mode
		// TODO - Ability to change this image from config / domain ?
		-> add_HTMLEmbedded(ROOT. DS. 'htdocs'. DS. 'img'. DS. 'cargohub-email.png', 'powered.by@cargohub.aero');

		// Embeds and real Attachments
		if(is_array($embeds) && count($embeds)>0) {
			foreach($embeds as $c=> $emb) {
				$mm-> add_HTMLEmbedded(ROOT. DS. $emb, "embed{$c}@{$tpldata['domain']}");
			}
		}

		// Attach files to the e-mail itself if the cloud files option was not specified
		if(!empty($attachments) && empty($options['cloud'])) {
			foreach($attachments as $att) {
				// Add a file from the warehouse to be sent as attachment.
				// (I don't like this - Path is hardcoded, there should be a better way...)
				$fullpath = ROOT. DS. 'warehouse_mount';
				for($c = 0; $c< 2; $c++)
					$fullpath.= DS. $att['chash'][$c];
				$fullpath.= DS.$att['chash'].'.'.$att['ext'];
 				$mm-> add_Attachment($fullpath, $att['name']);
			}
		}


 
		$sent = $mm-> send();
		
		 

		// Update the message so it is marked as sent by e-mail.
		if($update_status) {
			if($sent)
				$this-> update($msg_id, array(
					'email_status'=> "sent"
//					'sender_ip'=> sprintf('%u', ip2long($_SERVER['REMOTE_ADDR'])) // TODO: This method might be used internally by the system itself (Cron); There won't be any sender IP !
				));
			else
				$this-> update($msg_id, array('email_status'=> "failed"));
		}
		if(empty($options['extret']))
			$ret = $sent;
		else
			$ret['sent'] = $sent;

		return $ret;
	}
