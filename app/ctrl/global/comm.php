	/**
	 * Request to send an E-mail to one or more recipients
	 * - Supports standard "To", "Cc" and "Bcc" type of recipients, which are all recorded
	 * - Ability to link the E-mail to a data record (using conversations) (TODO: Optional)
	 * - Sending options affect how the message is built (TODO: Optional)
	 *
	 * Beside sending the e-mail, it also records the conversation and message in the database, and return the conversation ID as the JSON response
	 * If the request contains a conversation ID, it links the message to the existing conversation and updates contacts
	 * TODO: Support using this function without being logged in (as an user)
	 */
	public function action_Sendmail(MVC_Request $rq) 
	{
		$user = MVC_Core::$ss-> user; // Current logged in user, he/she becomes the sender of the message - Or $user is null if there's no logged in user.
		$org_id = (int)($rq-> org_id? $rq-> org_id: (!empty($user)? $user['org_id']: null));

		// Check sender contact
		$sender = $this-> con-> read($rq-> sender_id, false);
		if(!$sender)
			return $this-> send_Fail_JSON("Sender contact could not be located in the database.");

		// Decode parameters
		$recipients = @json_decode($rq-> recipients, true);
		if(!$recipients)
			return header("HTTP/1.0 500 Error encountered while decoding the recipients list");

		$link = @json_decode($rq-> link, true);
		if(!$link)
			return header("HTTP/1.0 500 Error encountered while decoding the message linking information");

		$options = @json_decode($rq-> options, true);
		if(!$options)
			return header("HTTP/1.0 500 Error encountered while decoding the send options");

		// Create the message with the incoming data - Source is "Send mail", this message is intended to be sent as an e-mail
		$source_msg = array(
			'org_id'=> $org_id,
			'from_id'=> (int)$sender['id'],
			'sender_ip'=> sprintf('%u', ip2long($_SERVER['REMOTE_ADDR']))
		);


		// Recipients processing:
		// - If ID's are present, then they are used directly
		// - If just e-mail addresses, an attempt is made to locate the e-mail address in the existing contacts
		$r_ids = array();
		$c_linked_ctx = 0;
		$orglinks = array();
		foreach($recipients as $r_group=> $r_list)
			foreach($r_list as $r_con) {
				if(isset($r_con['id'])) {
					// When the method is asked to share the record ($link), read each contact individually and determine if it's a special contact used as target for sharing the record
					// If the contact is a target and matches rt_Key, the record will be shared (target organization added). This might also trigger extra E-mail as notifications to subscribers for those record types
					// This only happens when the contact is in the primary list ( To: ) - Using Cc: / Bcc: skips it in the auto-sharing mechanism
					if($options['share'] && $r_group == "to") {
						// Save organization link information, it will be checked after conversation creation for: Automatic Response E-mail (arem)
						$orglinks[] = $this-> share_Record($link, $r_con, $sender, true);
					}

				} else {
					// Create the contact
					$r_con['id'] = $this-> con-> create(
						!empty($user)? "personal": "isslink", // Set it as personal for the user sending it ? Or just linked to the record if this is not sent by an user
						$org_id, array(
							'email'=> $r_con['email'],
							'name'=> $r_con['name'],
							'xdata'=> array(
								'rem'=> sprintf("Auto-generated by sending a message linked to record: %s", $link['track'])
							),
							'count_msgs'=> 0
						), !empty($user)? $user['id']: null
					);

					// Well, if even create failed, there's a serious problem - Abort sending the message
					if(empty($r_con['id']))
						return header("HTTP/1.0 500 Unable to store contact information for address {$r_con['email']}. Sending not possible");
				}

				// Link all recipient contacts to the record (if not already linked) - Bcc's are not linked
				if($options['contacts'] && $r_group != "bcc") {
					$r = $this-> con-> con2iss_Create($link['id'], $r_con['id'], array(
						'role'=> 'recipient',
						'label'=> "E-mail recipient",
						'visibility'=> "org", // Contacts are initially visible only to the organization that sent the message
						'org_id'=> $org_id,
						'user_id'=> !empty($user)? $user['id']: null
					), false);
					if(!empty($r))
						$c_linked_ctx++;
				}

				if(empty($r_ids[$r_group]))
					$r_ids[$r_group] = array();
				$r_ids[$r_group][] = (int)$r_con['id'];
			}
		$source_msg['recipients'] = $r_ids; // Array of "to", "cc", "bb" - The sender can ses the complete list. All recipients however will get "bcc" removed from their copy of the message

		if(!empty($options['selfcopy'])) {
			if(!isset($source_msg['recipients']['bcc']))
				$source_msg['recipients']['bcc'] = array();
			$source_msg['recipients']['bcc'][] = (int)$sender['id'];
		}

		// Attachments processing (All these have been pre-uploaded, and only need to be linked to the message after the message is successfully created)
		if($rq-> attachments) {
			$attachments = explode(',', $rq-> attachments['ids']);
			$attachments_size = (int)$rq-> attachments['size'];
			$source_msg['count_files'] = count($attachments);
		}

		if(!empty($user)) {
			// When logged in, the message is connected to the user (and his organization)
			if(!empty($user['sentbox_id']))
				$source_msg['con_id'] = $user['sentbox_id'];
		} else {
			// No user - This message is sent by an outside contact through a form (Not yet used)
		}

	/* SOURCE MESSAGE - Copy of the message for the sender */



		$src_iid = $this-> comm-> create('sendmail', $rq-> body, empty($rq-> subject)? null: $rq-> subject, $source_msg);
		if(!$src_iid)
			return header("HTTP/1.0 500 Database error: Unable to record the message: Send not possible");
 
		// Success ! Source message recorded - Increase the count for User (if there's an user) and for Organization
		if(!empty($user)) {
			$q= QueryFactory::update()
				-> table(MVC_Core::$db-> tab['usr'])
				-> values(array(
					'count_msgs'=> "`count_msgs`+1"
				), null, true)
				-> where("`id` = ?", $user['id']);

			MVC_Core::$db-> query($q);
		}

		// Attachments
		if(!empty($attachments)) {
			$this-> factory_Model('File');
			$this-> file-> update_Extra($attachments, array(
				'linked_with'=> "message",
				'linked_id'=> $src_iid
			));
		}


		// Update the organization information - Message counter, File counter and Total storage space for these sent files
		if(!empty($org_id)) {
			$org_update = array(
				'count_msgs'=> "`count_msgs`+1"
			);
			if(!empty($attachments)) {
				$org_update['count_files'] = "`count_files`+ ".count($attachments);
				$org_update['files_total_kbytes'] = "`files_total_kbytes`+ ".(int)round($attachments_size/1024);
			}

			$q= QueryFactory::update()
				-> table(MVC_Core::$db-> tab['org'])
				-> values($org_update, null, true)
				-> where("`id` = ?", $org_id);

			 MVC_Core::$db-> query($q);
		}

		// TODO: Support conversations which are not linked to another entity ( like a record )

	// SOURCE CONVERSATION - When linked to records, the messages are actually grouped into chains, called conversations

		// Create the conversation from the message, marking it as started by the logged in user and directed toward the recipient
		$cnv_iid = $this-> cnv-> create($link['type'], $src_iid, $link['id'], true, true);
		if(!$cnv_iid)
			return header("HTTP/1.0 500 Database error: Unable to setup the communication and send the message");

	/* TODO: TARGET MESSAGE(s) - Creates copies of the source message in the database, for each contact which is specified in the recipients */

	/* TODO: TARGET CONVERSATION - When the recipient is a target e-mail for data sharing, a new conversation is created from the Target Message, but on the recipient size */

		// This resolves the security issue of organization seeing somebody else's messages - With the new system, every conversation is only visible to the organization it is intended for
		// The current system of conversation sharing will no longer be used, as copies of the messages will exist for all involved parties ( and can be managed independently, or deleted, without affecting the others )

	/* E-MAIL - Finally, with all data recorded, send the source message as an e-mail */

 

		$options['extret'] = true;
		// Send via PHPMailer
		$ret = $this-> comm-> msg_Mailer($src_iid, $options);
		if(!$ret || empty($ret['sent'])) {
			// Make the conversation hidden, to avoid the confusion that the message was send when in reality it was not
			// TODO: This is temporary, because conversations are supposed to be about multiple messages, not just one... but still, right now conversations only have one single message
			$this-> cnv-> update($cnv_iid, array(
				'visibility'=> "hidden"
			));

			return header("HTTP/1.0 500 E-mail system was unable to send your message. The error is recorded. You may try to send again or contact support.");
		}
		
		 

		// Update record metadata (increase convos by 1, update sui_* metadata)
		$this-> record-> update($link['id'], array(
			'sui_lmid'=> $src_iid,
			'sui_lmdt'=> date("Y-m-d H:i:s"),
			'sui_lmctx'=> json_encode($ret)
		));

		$this-> record-> org_UpdateData($link['id'], $org_id, array(
			// TODO: Count messages
			'utime'=> date("Y-m-d H:i:s")
		), true); // Don't recheck locator

// @DEPRECATED		$this-> record-> counter_Update($link['id'], 1, 0, 0, 0, $c_linked_ctx);

		// Everything worked, patch in the Autoresponse message if any of the linked organizations have one.
		if(!empty($orglinks))
			foreach($orglinks as $orglink) {
				// This will read the record again in order to generate the message
				//                                Organization ID     Organization Type            Record ID              Delay (not yet used)
				$arem_sent = $this-> arem_Trigger($orglink['org_id'], $orglink['type_id'], 'recv', $link['id'], $sender, $cnv_iid, 1800);
			}

		// TODO: Figure out the recipients stuff and know if it's singular or plural... duh!
		$response = "The message was sent to the recipient(s).";
		return $this-> send_JSON(array("success"=> true, "response"=> $response));
	}

	/**
	 * Connects the target organization to the record when an e-mail is sent to one of the special "target contacts"
	 * (Eventually move the public version to this controller. Dupe: /public/issuephp::share_Record_v2)
	 *
	 * @param array $link The record to which a message is linked
	 * @param array $recipient Which target contact was used to determine that sharing should happen ?
	 * @param array $sender Sender contact Who performed the sharing ?
	 * @param bool $with_message
	 * @return boolean
	 */
	protected function share_Record($link, $recipient, $sender = null, $with_message = false)
	{
		if(empty($link['id']))
			return false; // Error, no record ID present ?

		$target_org = $this-> org-> targetContact_Check($recipient['id'], $link['rt_key']);
		if(empty($target_org))
			return false; // $recipient is not a target contact. Nothing to do

		// Found a valid target contact ! Should contain org_id (int), dep_ids (array) - Information used for share linking; Do the auto-sharing.
		$orglink = $this-> record-> org_Add($link['id'], $target_org['org_id'], $target_org['dep_ids'], array(
			'commtime'=> $with_message? time(): null
		), true, false, false, 'recv'); // Receive mode, since this is a share

		// Add was successful. Update current organization to indicate that sharing was performed (also update process marker to "shared")
		if(is_array($orglink) && !isset($orglink['previously_linked'])) {
			$this-> record-> org_UpdateData($link['id'], $sender['org_id'], array(
				'process'=> "shared",
				'xfer_by'=> $sender['id'],
				'xfer_to'=> $recipient['id'],
				'xfer_time'=> time(),
				'xfer_ip'=> sprintf('%u', ip2long($_SERVER['REMOTE_ADDR']))
			), true);
		}

		return $orglink;
	}

	/**
	 * Attempts to resend the message with id $rq-> msg_id as an E-mail
	 * - The message is sent under identical conditions as when it was created (same recipients, attachments, subject and content)
	 * - However, since options are not present here, it sends with some defaults - Signature of the logged in user (instead of the original sender signature);
	 * - Attachments are send in "cloud" mode (as links).
	 *
	 * @param MVC_Request $rq
	 */
	public function action_Resend_Message(MVC_Request $rq)
	{
		if(empty(MVC_Core::$ss-> user))
			return $this-> send_Fail_JSON("This function is only available when logged in.");

		if(empty($rq-> msg_id))

			return $this-> send_Fail_JSON("Request doesn't contain the message ID.");

		$r = $this-> comm-> msg_Mailer($rq-> msg_id, array(
			'attachments'=> true,
			'signature'=> !empty(MVC_Core::$ss-> user['preferences']['operations']['email_cc']),
			'cloud'=> true,
			'status'=> false
		));
		if(!$r) {
			$err = MVC_Core::$debug-> get_Last_Dump();
			if($err['label'] == 'App_Model_Comm::msg_Mailer')
				return header(sprintf("HTTP/1.0 500 %s", $err['data']));
			else
				// Unknown error, not recorded by the debug system
				return header("HTTP/1.0 500 E-mail system was unable to resend the message. Please try again later");
		}


		//IWI to view sender details, resend mail and print this mail in add / edit message start  21022025 add by iwi
			$source_msg = array();
			$details = $this->comm->read($rq->msg_id,array("meta","content"));
			foreach ($details as $key => $val) {
				$source_msg[$key] = $val;
			}
			unset($source_msg['id']);
			unset($source_msg['dt']);
			$source_msg['sender_ip'] = sprintf('%u', ip2long($_SERVER['REMOTE_ADDR']));
			$q = QueryFactory::insert()
					->table(MVC_Core::$db->tab['msg'])
					->values($source_msg);
			$r = MVC_Core::$db->query($q);
		//IWI to view sender details, resend mail and print this mail in add / edit message end  21022025 add by iwi

		// TODO: Figure out the recipients stuff and know if it's singular or plural... duh!
		$response = "The message was sent to the recipient(s).";
		return $this-> send_JSON(array("success"=> true, "response"=> $response));
	}

	/**
	 * Automatic Responder Mail - Locates tempplates for automatic mailing following an event ( like receiving record )
	 *
	 * @param int $org_id Organization data
	 * @param string $org_type_id Type of organization (matching $org_id) - Necessary to determine which trigger keyword is used
	 * @param string $event Event for which templates are located
	 * @param int $rec_id Record id
	 * @param int $cnv_id Conversation ID: If present, link the response to this conversation instead of creating a new one
	 * @param int $delay Delay in seconds until the message is being generated/triggered (Use Skynet queue for messages)
	 * @return bool|array If a template was found, template information is returned. If it failed or there are none, it returns false
	 */
	private function arem_Trigger($org_id, $org_type_id, $event, $rec_id, $sender, $cnv_id = null, $delay = null)
	{
		if(!in_array($event, array('recv')))
			return MVC_Core::$debug-> dump(sprintf("Unsupported automatic mail event: %s", $event), __METHOD__, null, 'error');

		$this-> record-> cache_Reset();
		// serialize_source => Also retreive normal version of xfields (unserialized), in field "xfields_source"
		$rec = $this-> record-> read($rec_id, array('issue', 'group', 'xfields', 'submitter', 'organization'), null, null, null, array('serialize'=> true, 'serialize_source'=> true));

		// Use the record plugin to determine the keyword which will decide which notification (if any) is used
		if(!empty($this-> record-> rec_plugin) && method_exists($this-> record-> rec_plugin, "arem_Keyword")) {
			$keyword = $this-> record-> rec_plugin-> arem_Keyword($rec, $org_type_id, true); // True = Use "xfields_source" instead of "xfields"
		} else
			return MVC_Core::$debug-> dump("Triggering keyword is necessary for this method", __METHOD__, null, 'error');

		// Load any "arem" templates for the specified record type ID
		$m_tpl = new App_Model_Template();
		$r = $m_tpl-> get_List($org_id, array('template', 'body'), function(QueryFactory &$q) use ($rec) {
			$q
			-> where("`tpl`.role = 'arem'")
			-> where("`tpl`.rt_id = ?", $rec['type_id']);
		});

		if(empty($r))
			return false; // No templates found or error occured during read

		foreach($r as $row) {
			// Post-process
			$row['id'] = (int)$row['id'];
			if(empty($row['description']))
				$row['description'] = $row['title'];

			// decode xdata
			if(!empty($row['xdata'])) {
				$row['xdata'] = json_decode($row['xdata'], true);

				// Check if event matches
				if($row['xdata']['arem_event'] == $event && $row['xdata']['arem_kw'] == $keyword) {
					// Found it !
					$template = $row;
					break;
				}
			}
		}

		if(!isset($template))
			return MVC_Core::$debug-> dump(sprintf("Out of %d AREM templates found, none of them match the keyword %s", count($r), $keyword), __METHOD__, null, 'notice');

		// Construct the message based on the template and record data, then use the mentioned "arem_contact" as the sender, and send the message
		// Note: This uses the new mailer. TODO: Replace issue2message with the new mailer as well (PHPMailer)

		// Assamble the message contents
		$tpl_data = array(
			'domain'=> MVC_Core::$ss-> domain_CFG['domain'],
			'html'=> MVC_Core::$ss-> domain_CFG['html_settings'],
			'organization'=> $rec['organization']
		);

		// Find a way to replace "issue" with "record" and "ist" with "rt" in all templates... ?
		$tpl_data['issue'] = $rec;
		$tpl_data['ist'] = $this-> record-> ist_Read($rec['type_id']);

		$this-> init_Template_System();

		try {
			$template['title'] = $this->_drytpl-> render_String($template['title'], $tpl_data);
			$template['body'] = $this->_drytpl-> render_String($template['body'], $tpl_data);
		} catch(Exception $e) {
			// Error during render ? Probably bad template
			return MVC_Core::$debug-> dump("Template rendering error - Unable to respond", __METHOD__, null, 'error');
		}

		// $emplate should now be actual content, ready to be assembled into a message and then mailed
		$msg_meta = array(
			'org_id'=> $org_id,
			'from_id'=> $template['xdata']['arem_contact'],
			'recipients'=> array(
				'to'=> array($sender['id'])
			)
		);
		if(!empty($cnv_id))
			$msg_meta['cnv_id'] = $cnv_id;

		$msg_iid = $this-> comm-> create('issreply', $template['body'], $template['title'], $msg_meta);
		if(!$msg_iid)
			return MVC_Core::$debug-> dump("Database error: Unable to record the message: Send not possible", __METHOD__, null, 'error');

		if(empty($cnv_id)) {
			// When no pre-existing conversation is specified, create a new conversation to connect the message to the record
			$this-> cnv = $this-> factory_Model("Conversation", "cnv");
			$cnv_id = $this-> cnv-> create('issue', $msg_iid, $rec_id, true, true);
		} else
			// Attach the message to the existing convo
			$this-> cnv-> attach($cnv_id, $msg_iid);

		$this-> record-> counter_Update($rec_id, 1);

		// Use PHPMailer to send the message to the internetz
		return $this-> comm-> msg_Mailer($msg_iid);
	}
        
        
        
       


