	// exported methods
	this._public({
		/**
		 * Set this as a callback before running Setup - It will be called when dependencies finished loading (and Compose is considered initialzied)
		 */
		on_Ready: null,

		/**
		 * If "rich_editor" dependency finished initializing, it should return true. The editor is ready to receive values
		 */
		is_Ready: function()
		{
			return rich_editor_ready;
		},

		/**
		 * Setup the reusable widget
		 *
		 * @param $container The jQuery object representing the container inside which the widget will be initialized
		 * @param _config The configuration for this widget
		 * @param _dependencies Other components needed by this one (Currently only TinyMCE)
		 * @param _master Module which called this function. Used by the callbacks [Optional] - If missing the callbacks are disabled
		 */
		setup: function(_config, _dependencies, _master)
		{
			config = _config;
			if(!config.container || config.container.length != 1)
				return cargohub.alert("Error: Setup of Compose E-mail component failed. Container was not specified, not found or non-unique match found");
			$c = config.container;
			delete config.container;

			if(!_dependencies.rich_editor)
				return cargohub.alert("Error: Setup of Compose E-mail component failed. Rich editor (TinyMCE) component object must be loaded");
			rich_editor = _dependencies.rich_editor;
			// Instance key defaults to this component's own name if not specified
			rich_editor_instance_key = config.rich_editor_instance_key||"components_compose";

			if(_master)
				master = _master;

			setup_Recipients();
			setup_Subject();
			setup_Contents(_dependencies.rich_editor, config.rich_editor_instance_key||"components_compose");
		},

		/**
		 * Clears the Compose of contacts, subject and body - Allows fresh e-mail to be started.
		 */
		reset: function()
		{
			// Clear all recipients
			$("#message-recipients div.con-sortable", $c).empty().addClass('con-empty');

			// Hide cc/bcc lines and show the buttons again
			$("#rec-cc, #rec-bcc", $c).fadeOut();
			$("#rec-to > div", $c).width(970);
			$("#recipients-cc, #recipients-bcc", $c).fadeIn();
			cc_open = false; bcc_open = false;

			// Reset subject and body
			$("#message-subject > input", $c).val('');
			rich_editor.content_Write(rich_editor_instance_key,'');

			// If templates selector is open, close it:
			if(templates_selector) {
				// Destroy the selector, hide the div, show the input
				$("#message-subject > input", $c).show();
				$("#message-subject > div", $c).off('select').jqxDropDownList('destroy');

				templates_selector = false;
			}

			has_contents = false;
			changed = false;
			changed_edit = false;
		},

		/**
		 * Component API: Adds one or more contacts to one of the contact lines, just like it was typed from the temporary input
		 *
		 * @param input_string A string, should contain one or more e-mail addresses. If no addresses, the contact box(es) may be added as an error
		 */
		add_Contacts: function(input, con_line)
		{
			if(!input)
				return; // Empty input, nothing to do

			if(!con_line) {
				// Determine if there's anything on To: ; If not, first contact goes on To, the next on Cc ; If To: has at least one contact, everything goes to Cc:

				var to_line_length = $("#message-recipients > div#rec-to > div.con-sortable", $c).children().length;
				if(to_line_length == 0) {
					if($.isArray(input)) {
						// Extract first item ( goes on To ), rest go to "Cc"
						var first_con = input.pop();
							self.add_Contacts(first_con, 'to');
						// Just let if flow for the next elements
						con_line = 'cc';
					} else
						// Not an array, it simply goes to to:
						con_line = 'to';
				} else
					con_line = 'cc';
			} else
				con_line = con_line.toLowerCase();

			if(con_line!='to' && con_line!='cc' && con_line!='bcc')
				return -1; // Invalid con_line detected

			var $con_line = $("#message-recipients > div#rec-"+ con_line+ " > div.con-sortable", $c);
			// Make sure the line is visible
			if(con_line != 'to')
				$("#recipients-"+ con_line, $c).trigger('click');

			// Determine what type of input:
			// - String (Let the server determine)
			// - Object (Single contact data, add a contact box with data set - no server call)
			// - Array with strings (Call the server for each one)
			// - Array with objects (Add the multiple contact boxes with data set - no server call)
			if($.isArray(input))
				for(var c=0; c<input.length; c++)
					self.add_Contacts(input[c], con_line); // Recursive trick
			else {
				if(typeof input === 'object') {
					if(!input.email)
						return; // Email is mandatory here, fail silently if not present

					if(contacts_Scan_Email(input.email))
						return cargohub.alert("This e-mail already exists in the list of recipients", input.email, "stock_mail_copy.png ");

					// No scan here, assumes contacts are properly set - Just add it to $con_line
					var $con_block = $('<span class="ui-state-default"></span>').text(input.name? input.name: input.email).append(!input.name? "<i>; </i>": "<i> &lt;"+ input.email+ "&gt;; </i>");

					//+' <'+input.email+'>'
					if(input.id)
						$con_block.data('id', input.id);
					else
						$con_block.attr('title', input.email);

					$con_line.append($con_block);
				} else
					scan_For_Contacts($con_line, input);
			}
			// We added something, remove the empty marker
			$con_line.removeClass('con-empty');
		},

		/**
		 * Component API: Returns an object with valid contacts on the To, Cc and Bcc lines
		 * - If any contact anywhere has error (not a valid contact or email), the "errors" array is created - it contains the texts in those errored contacts
		 * - The caller method might choose to proceed even with errors (for example, silently discarding errors while keeping good results)
		 */
		get_Contacts: function()
		{
			var ctx = {}, rec = null, con = null, text = null, id = null;

			$("#message-recipients div.con-sortable > span").each(function() {
				text = $(this).text().slice(0, -2);
				con = contact_Scan_Text(text); // Skip the ;_ at the end
				if(con === false) {
					if(!ctx.errors)
						ctx.errors = [];
					ctx.errors.push(text);
				} else {
					id = $(this).data('id');
					if(id)
						con.id = id;

					rec = $(this).parent().parent().prop('id').substr(4);
					if(!ctx[rec])
						ctx[rec] = [];

					ctx[rec].push(con);
				}
			});
			return ctx;
		},

		/**
		 * Sets a string as the current subject (overrides existing)
		 */
		set_Subject: function(subject)
		{
			$("#message-subject input", $c).removeClass('gray').val(subject);
		},

		/**
		 * Reads the email subject. If the templates selector is still open, close it first.
		 * @returns string
		 */
		get_Subject: function()
		{
			if(templates_selector)
				$("#template-toggle", $c).trigger('click');

			return $.trim($("#message-subject input", $c).val());
		},

		/**
		 * Sets the body content to a new value (overrides existing)
		 */
		set_Body: function(body)
		{
			rich_editor.content_Write(rich_editor_instance_key, body);
		},

		/**
		 * Returns the current body of the Compose (from the rich_editor)
		 * @returns string
		 */
		get_Body: function()
		{
			return rich_editor.content_Read(rich_editor_instance_key);
		},

		/**
		 * Returns all contents from the Compose - Recipients, Subject, Body as well as any "plugin" type controls ( like the Include Signature checkbox )
		 *
		 * @param test_mode If true, it ignores any errors and continues anyway.
		 * @returns object
		 */
		get_Message: function(test_mode)
		{
			var message = {};

			message.recipients = self.get_Contacts();
			if(!test_mode && (!message.recipients || sizeof(message.recipients)==0))
				return cargohub.alert("No valid contacts detected. Add at least one <b>To:</b> recipient");

			if(!test_mode && (!message.recipients.to || message.recipients.to.length == 0))
				return cargohub.alert("There should be at least one <b>To:</b> recipient");

			if(!test_mode && message.recipients && message.recipients.errors && message.recipients.errors.length > 0)
				return cargohub.alert("Certain contacts have errors (invalid, no e-mails). Please check");

			message.subject = self.get_Subject();
			if(!test_mode && (!message.subject || message.subject.length < 3))
				return cargohub.alert("The message <b>Subject</b> may not be empty. Please write it!");

			message.body = self.get_Body(); // Allow empty body here - no error
			if(!test_mode && (!message.body || message.body.length < 3))
				return cargohub.alert("Please write your message, it is currently empty.");

			return message;
		},

	});

