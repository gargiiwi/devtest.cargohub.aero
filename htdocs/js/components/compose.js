	/**
	 * Prepares the Subject / Template line
	 */
	setup_Subject = function()
	{
		// Message subject (changes text color from inactive to active - only when content is empty)
		$("#message-subject > input", $c)
		.on('focus', function() {
			$(this).removeClass('gray');
		})
		.on('blur', function() {
			if(!$(this).val())
				$(this).addClass('gray');
		})
		.on('change', function() {
			changed = true;
			changed_edit = true;
			if($(this).val())
				has_content = true;
		});

		$("#template-toggle", $c)
		/**
		 * Event: Templates selector icon is clicked - Change the subject line into a selector for Message Templates (or back if nothing is selected)
		 */
		.on('click', function() {
			// Is it already on ?
			if(templates_selector) {
				// Destroy the selector, hide the div, show the input
				$("#message-subject > input", $c).show();
				$("#message-subject > div", $c).off('select').jqxDropDownList('destroy');

				templates_selector = false;
			} else {
				// Extra data for the dataAdapter - Is only available after setup() method
				templates_Source._source.data = {
					role: "email",							// Load just e-mail templates
					include_default: false,
//					org_id: config.org_id,	// Only relevant when superuser is logged in
					rt_id: config.link.rt_id
				};

				// Hide the input
				$("#message-subject > input", $c).hide();

				// Instance the selector
				$("#message-subject", $c).append('<div id="canned_select"></div>');
				$("#message-subject > div", $c).jqxDropDownList({
					theme: cargohub.jqxtheme,
					source: templates_Source,
					displayMember: "description", valueMember: "id",
					placeHolder: "(Loading templates)",
					width: 1060, dropDownWidth: 1060,
					animationType: "fade", enableBrowserBoundsDetection: true,
					disabled: true
				})
				/**
				 * Event: The list of templates has finished loading - Enabled the selector
				 */
				.on('bindingComplete', function() {
					if(templates_Source.records.length == 0)
						$(this).jqxDropDownList({
							placeHolder: "(There are no organization E-mail templates for this record type)",
							disabled: true
						});
					else {
						$(this).jqxDropDownList({
							placeHolder: "Select a template to set Title and Subject <b>(Does NOT include automatic record data)</b>:",
							dropDownHeight: templates_Source.records.length> 7? 184: null,
							autoDropDownHeight: templates_Source.records.length<= 7? true: false,
							disabled: false
						});
					}
				})
				/**
				 * Event: An e-mail template is selected. Grab the information and destroy the dropdown to save memory.
				 */
				.on("select", function(e) {
					if (e.args && e.args.item) {
						// Check if Compose was already changed - Give a warning that override will happen
						if(has_contents)
							if(!confirm("E-mail compose was already edited or contains preset contents.\nAre you sure you want to overwrite with new template?"))
								return;

						// Template was selected - Read the rendered template (Title/Body) and setup e-mail
						$.get("/global/operations?action=Render_Template", {
							id: e.args.item.originalItem.id,
							org_id: config.org_id,
							rt_id: config.link.rt_id,
							rec_id: config.link.rec_id
						}, function(r, textStatus, jqXHR) {

							$("#message-subject > input", $c).removeClass('gray').val(r.title);
							rich_editor.content_Write(rich_editor_instance_key, r.body);

							// Short timeout before focus to allow TinyMCE to sort itself out
							setTimeout(function() {
								$("#template-toggle", $c).trigger('click');
								rich_editor.focus(rich_editor_instance_key);
							}, 100);
							changed = true;
							has_contents = true;

						}, 'json')
						.fail(cargohub.its.http_fail);
					}
				});

				templates_selector = true;
			}
		})
		// Tooltip
		.jqxTooltip({
			theme: cargohub.jqxtheme,
			content: "<b>Toggle message templates selector</b><br />First click turns it on, another click shows the Subject line again.",
			position: 'bottom-left',
			left: 7
		});
	},

